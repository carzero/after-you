import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import sharp from 'sharp';
const root=new URL('../assets/source/art-20261121/',import.meta.url),out=new URL('../assets/runtime/art-20261121/',import.meta.url);
const manifest=JSON.parse(await fs.readFile(new URL('ASSET_MANIFEST.json',root)));
const map=JSON.parse(await fs.readFile(new URL('integration-map.json',root)));
const key=file=>file.replace(/^assets\//,'').replace(/^ui-kit\/art\//,'ui/').replace(/\.png$/,'');
const extra=['after_you','inspect','relief'];
const common=['rescue/cushion_v01','rescue/cushion_front_v01','rescue/box_v01','rescue/box_front_v01','rescue/worker_v01','vfx/takeoff_v01','vfx/landing_v01','vfx/rescue_v01','props/no_flying_v001','branding/app_icon','staff/guide'];
const selected=new Set(common.map(p=>'assets/'+p+'.png'));
for(const[id,poses]of Object.entries(map.characters)){for(const file of Object.values(poses))selected.add(file);for(const pose of extra)selected.add(`assets/characters/${id}/${pose}.png`);}
for(const layers of Object.values(map.chapters))for(const[role,file]of Object.entries(layers))if(role!=='entry')selected.add(file);
for(const id of ['title','invitation','stamp','potato','pigeon','duck','rabbit'])selected.add(`ui-kit/art/${id}.png`);
const sizes={};let total=0,count=0;
for(const entry of manifest){
 const source=new URL(entry.file,root),bytes=await fs.readFile(source);
 if(crypto.createHash('sha256').update(bytes).digest('hex')!==entry.sha256)throw Error(`Source hash mismatch: ${entry.file}`);
 if(!selected.has(entry.file))continue;
 const id=key(entry.file),target=new URL(id+'.webp',out);sizes[id]=[entry.width,entry.height];
 const width=/\/sky$/.test(id)?768:/^ui\/(potato|pigeon|duck|rabbit)$/.test(id)?256:/\/(tile|crack|collapse)$/.test(id)?320:512;
 await fs.mkdir(path.dirname(target.pathname),{recursive:true});
 const info=await sharp(bytes).resize({width,withoutEnlargement:true}).webp({quality:86,alphaQuality:100}).toFile(target.pathname);total+=info.size;count++;
}
if(count!==selected.size)throw Error('Some selected image paths were absent from manifest');
const icons=JSON.parse(await fs.readFile(new URL('ui-kit/manifest.json',root)));
for(const entry of icons){
 const text=await fs.readFile(new URL('ui-kit/'+entry.file,root),'utf8');
 if(/<\s*(script|foreignObject|image|use)\b|\son\w+\s*=|(?:href|src)\s*=/i.test(text))throw Error('Unsupported active SVG: '+entry.file);
 await fs.mkdir(new URL('icons/',out),{recursive:true});await fs.writeFile(new URL(`icons/${entry.id}.svg`,out),text);
}
const catalog={version:'20261121',characters:Object.fromEntries(Object.entries(map.characters).map(([id,poses])=>[id,Object.fromEntries([...Object.entries(poses).map(([p,f])=>[p,key(f)]),...extra.map(p=>[p,`characters/${id}/${p}`])])])),chapters:Object.fromEntries(Object.entries(map.chapters).map(([id,layers])=>[id,Object.fromEntries(Object.entries(layers).filter(([p])=>p!=='entry').map(([p,f])=>[p,key(f)]))])),common:common,sizes};
await fs.writeFile(new URL('../src/art-catalog.js',import.meta.url),'// Generated by npm run art:prepare; source PNGs are draft artwork.\nexport const catalog = '+JSON.stringify(catalog,null,2)+';\n');
console.log(`Verified ${manifest.length} source hashes; ${count} WebP + ${icons.length} SVG; ${(total/1024).toFixed(0)} KiB`);
